export function getTranslation(lang: Language, key: string): string {
  const langMap = translations[lang] || translations.English;
  if (langMap[key]) return langMap[key];
  if (translations.English[key]) return translations.English[key];
  return key;
}

/**
 * Detect initial language: Check user's manual selection in localStorage first,
 * or fallback to browser navigator.language detection.
 */
export function detectInitialLanguage(): Language {
  if (typeof window === 'undefined') return 'English';

  try {
    const saved = localStorage.getItem('mcbp_lang');
    if (saved && saved in translations) {
      return saved as Language;
    }

    const browserLang = (navigator.language || (navigator as any).userLanguage || '').toLowerCase();

    if (browserLang.startsWith('ru')) return 'Russian';
    if (browserLang.startsWith('es')) return 'Spanish';
    if (browserLang.startsWith('de')) return 'German';
    if (browserLang.startsWith('fr')) return 'French';
    if (browserLang.startsWith('zh')) return 'Chinese';
    if (browserLang.startsWith('ja')) return 'Japanese';
    if (browserLang.startsWith('pt')) return 'Portuguese';
    if (browserLang.startsWith('it')) return 'Italian';
    if (browserLang.startsWith('ko')) return 'Korean';
  } catch (e) {
    // Ignore SSR or localStorage access restriction errors
  }

  return 'English';
}

/**
 * Persists the user's manual language choice in localStorage.
 */
export function saveUserLanguage(lang: Language): void {
  try {
    if (typeof window !== 'undefined') {
      localStorage.setItem('mcbp_lang', lang);
    }
  } catch (e) {
    // Ignore localStorage write errors
  }
}
